using System.Globalization;
using System.Text;

namespace Meridian.Wire.Gen;

/// <summary>Turns a parsed <see cref="Schema"/> into C# source.</summary>
internal static class Emitter
{
    private static readonly Dictionary<string, (string CsType, string Method)> PrimitiveMap = new(StringComparer.Ordinal)
    {
        ["u8"] = ("byte", "U8"),
        ["u16"] = ("ushort", "U16"),
        ["u32"] = ("uint", "U32"),
        ["u64"] = ("ulong", "U64"),
        ["i16"] = ("short", "I16"),
        ["i32"] = ("int", "I32"),
        ["i64"] = ("long", "I64"),
        ["bool"] = ("bool", "Bool"),
        ["varu32"] = ("uint", "VarU32"),
        ["vari32"] = ("int", "VarI32"),
    };

    private static readonly (string Direction, string Interface)[] HandlerGroups =
    [
        ("ServerBound", "IServerBoundHandler"),
        ("ClientBound", "IClientBoundHandler"),
        ("Internal", "IInternalHandler"),
    ];

    public static string Emit(Schema schema)
    {
        var sb = new StringBuilder();
        sb.Append("""
            // <auto-generated>
            //   Generated by Meridian.Wire.Gen from Schema/messages.wire. Do not edit by hand.
            //   Regenerate: dotnet run --project src/Meridian.Wire.Gen
            // </auto-generated>
            #nullable enable

            namespace Meridian.Wire;

            /// <summary>Identity of the schema this code was generated from. Client and server must match.</summary>
            public static class WireSchema
            {

            """);
        sb.Append(CultureInfo.InvariantCulture, $"    public const ulong Hash = 0x{schema.Hash:X16}UL;\n");
        sb.Append("}\n");

        foreach (var d in schema.Definitions)
        {
            EmitType(sb, d);
        }
        foreach (var (direction, iface) in HandlerGroups)
        {
            EmitHandler(sb, schema, direction, iface);
        }
        EmitDispatch(sb, schema);
        return sb.ToString();
    }

    private static void EmitType(StringBuilder sb, Definition d)
    {
        var iface = d.IsMessage ? $"IWireMessage<{d.Name}>" : $"IWireStruct<{d.Name}>";
        sb.Append('\n');
        sb.Append(CultureInfo.InvariantCulture, $"public partial struct {d.Name} : {iface}\n{{\n");
        if (d.IsMessage)
        {
            sb.Append(CultureInfo.InvariantCulture, $"    public const ushort Id = {d.Id};\n\n");
            sb.Append(CultureInfo.InvariantCulture, $"    public static ushort MessageId => Id;\n\n");
            sb.Append(CultureInfo.InvariantCulture, $"    static Direction IWireMessage<{d.Name}>.Direction => Direction.{d.Direction};\n\n");
            sb.Append(CultureInfo.InvariantCulture, $"    static Delivery IWireMessage<{d.Name}>.Delivery => Delivery.{d.Delivery};\n\n");
        }

        foreach (var f in d.Fields)
        {
            sb.Append(CultureInfo.InvariantCulture, $"    public {CsType(f.Type)} {Pascal(f.Name)};\n\n");
        }

        // Write
        sb.Append("    public readonly void Write(ref WireWriter writer)\n    {\n");
        foreach (var f in d.Fields)
        {
            EmitWrite(sb, f, "        ");
        }
        sb.Append("    }\n\n");

        // Read
        sb.Append(CultureInfo.InvariantCulture, $"    public static {d.Name} Read(ref WireReader reader)\n    {{\n");
        sb.Append(CultureInfo.InvariantCulture, $"        var value = default({d.Name});\n");
        foreach (var f in d.Fields)
        {
            EmitRead(sb, f, "        ");
        }
        sb.Append("        return value;\n    }\n}\n");
    }

    private static void EmitWrite(StringBuilder sb, Field f, string indent)
    {
        var name = Pascal(f.Name);
        var t = f.Type;
        switch (t.Kind)
        {
            case "string":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}writer.WriteString({name}, {t.Max});\n");
                break;
            case "bytes":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}writer.WriteBytes({name}, {t.Max});\n");
                break;
            case "struct":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}{name}.Write(ref writer);\n");
                break;
            case "list":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}var {f.Name}Items = {name} ?? [];\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}writer.WriteCount({f.Name}Items.Length, {t.Max});\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}foreach (var item in {f.Name}Items)\n{indent}{{\n");
                sb.Append(PrimitiveMap.TryGetValue(t.Element!, out var p)
                    ? $"{indent}    writer.Write{p.Method}(item);\n"
                    : $"{indent}    item.Write(ref writer);\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}}}\n");
                break;
            default:
                sb.Append(CultureInfo.InvariantCulture, $"{indent}writer.Write{PrimitiveMap[t.Kind].Method}({name});\n");
                break;
        }
    }

    private static void EmitRead(StringBuilder sb, Field f, string indent)
    {
        var name = Pascal(f.Name);
        var t = f.Type;
        switch (t.Kind)
        {
            case "string":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}value.{name} = reader.ReadString({t.Max});\n");
                break;
            case "bytes":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}value.{name} = reader.ReadBytes({t.Max});\n");
                break;
            case "struct":
                sb.Append(CultureInfo.InvariantCulture, $"{indent}value.{name} = {t.Element}.Read(ref reader);\n");
                break;
            case "list":
                var elemType = PrimitiveMap.TryGetValue(t.Element!, out var p) ? p.CsType : t.Element!;
                var readExpr = p.Method is not null ? $"reader.Read{p.Method}()" : $"{t.Element}.Read(ref reader)";
                sb.Append(CultureInfo.InvariantCulture, $"{indent}var {f.Name}Count = reader.ReadCount({t.Max});\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}value.{name} = new {elemType}[{f.Name}Count];\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}for (var i = 0; i < {f.Name}Count; i++)\n{indent}{{\n");
                sb.Append(CultureInfo.InvariantCulture, $"{indent}    value.{name}[i] = {readExpr};\n{indent}}}\n");
                break;
            default:
                sb.Append(CultureInfo.InvariantCulture, $"{indent}value.{name} = reader.Read{PrimitiveMap[t.Kind].Method}();\n");
                break;
        }
    }

    private static void EmitHandler(StringBuilder sb, Schema schema, string direction, string iface)
    {
        sb.Append(CultureInfo.InvariantCulture, $"\n/// <summary>Receives {direction} messages from <see cref=\"WireDispatch\"/>.</summary>\n");
        sb.Append(CultureInfo.InvariantCulture, $"public interface {iface}<in TContext>\n{{\n");
        var first = true;
        foreach (var d in schema.Definitions.Where(d => d.IsMessage && d.Direction == direction))
        {
            if (!first)
            {
                sb.Append('\n');
            }
            first = false;
            sb.Append(CultureInfo.InvariantCulture, $"    void On{d.Name}(TContext context, in {d.Name} message);\n");
        }
        sb.Append("}\n");
    }

    private static void EmitDispatch(StringBuilder sb, Schema schema)
    {
        sb.Append("""

            /// <summary>
            /// Decodes one packet and calls the matching handler method. Throws <see cref="WireFormatException"/>
            /// for unknown ids, ids from the wrong direction, malformed bodies and trailing bytes.
            /// </summary>
            public static class WireDispatch
            {
            """);
        sb.Append('\n');
        var first = true;
        foreach (var (direction, iface) in HandlerGroups)
        {
            if (!first)
            {
                sb.Append('\n');
            }
            first = false;
            sb.Append(CultureInfo.InvariantCulture, $"    /// <returns>The id of the dispatched message.</returns>\n");
            sb.Append(CultureInfo.InvariantCulture, $"    public static ushort Dispatch{direction}<TContext>(System.ReadOnlySpan<byte> packet, {iface}<TContext> handler, TContext context)\n    {{\n");
            sb.Append("        System.ArgumentNullException.ThrowIfNull(handler);\n");
            sb.Append("        var reader = new WireReader(packet);\n        var id = reader.ReadU16();\n        switch (id)\n        {\n");
            foreach (var d in schema.Definitions.Where(d => d.IsMessage && d.Direction == direction))
            {
                sb.Append(CultureInfo.InvariantCulture, $"            case {d.Name}.Id:\n            {{\n");
                sb.Append(CultureInfo.InvariantCulture, $"                var message = {d.Name}.Read(ref reader);\n");
                sb.Append("                reader.EnsureEnd();\n");
                sb.Append(CultureInfo.InvariantCulture, $"                handler.On{d.Name}(context, message);\n");
                sb.Append("                return id;\n            }\n");
            }
            sb.Append(CultureInfo.InvariantCulture, $"            default:\n                throw new WireFormatException($\"Message id {{id}} is not a {direction} message.\");\n");
            sb.Append("        }\n    }\n");
        }
        sb.Append("}\n");
    }

    private static string CsType(FieldType t) => t.Kind switch
    {
        "string" => "string?",
        "bytes" => "byte[]?",
        "struct" => t.Element!,
        "list" => (PrimitiveMap.TryGetValue(t.Element!, out var p) ? p.CsType : t.Element!) + "[]?",
        _ => PrimitiveMap[t.Kind].CsType,
    };

    private static string Pascal(string camel) => char.ToUpperInvariant(camel[0]) + camel[1..];
}
